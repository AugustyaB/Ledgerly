/**
 * Builds a clean inline SVG icon element string.
 * @param {string} name - Icon name from ICON_PATHS.
 * @param {number} [size=20] - Dimensions in pixels.
 * @param {string} [cls=''] - Additional CSS classes.
 * @returns {string} SVG HTML string.
 */
export function icon(name, size = 20, cls = '') {
  const pathData = ICON_PATHS[name] || ICON_PATHS['zap'];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide-icon lucide-${name} ${cls}" aria-hidden="true">${pathData}</svg>`;
}

/**
 * Scans the container and hydratively replaces all [data-icon] elements.
 * @param {HTMLElement|Document} [root=document]
 */
export function hydrateMobileIcons(root = document) {
  const elements = root.querySelectorAll('[data-icon]');
  elements.forEach(el => {
    const iconName = el.getAttribute('data-icon');
    const size = parseInt(el.getAttribute('data-icon-size') || '20', 10);
    const customClass = el.getAttribute('data-icon-class') || '';
    if (iconName && ICON_PATHS[iconName]) {
      const existingBadge = el.querySelector('.dock-badge');
      el.innerHTML = icon(iconName, size, customClass);
      if (existingBadge) {
        el.appendChild(existingBadge);
      }
    }
  });
}
